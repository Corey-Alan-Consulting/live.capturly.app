#!/usr/bin/env node
// PreToolUse hook for Edit/Write/MultiEdit/NotebookEdit. Reads the tool call
// from stdin and prints a permission decision; exit 0 always.
//
//   deny  an edit that touches a framework sync block in CLAUDE.md/AGENTS.md:
//         the next sync overwrites it, so the fix belongs in framework.
//   ask   a protected path: .github/, prisma/migrations/, .env*/.envrc, and
//         this guard's own config. A human gets a prompt with the reason; a
//         headless session (claude -p, CI, the Tekton lanes) is refused.
//
// AGENT_GUARD_ALLOW=github,migrations,env,claude (in the claude process's
// environment, which an agent's Bash cannot change) lifts the "ask" for that
// class; the heal-rule lane sets `github` because workflow fixes are its job.
//
// Synced from framework/agents/hooks — fix it there, not here.
import { readFileSync } from 'node:fs';
import { basename, relative, resolve, sep } from 'node:path';

const input = JSON.parse(readFileSync(0, 'utf8'));
const root = resolve(process.env.CLAUDE_PROJECT_DIR || input.cwd || '.');
const tool = input.tool_name;
const t = input.tool_input ?? {};
const file = t.file_path || t.notebook_path;
if (!file) process.exit(0);
const rel = relative(root, resolve(root, file)).split(sep).join('/');

const decide = (permissionDecision, permissionDecisionReason) => {
  process.stdout.write(
    JSON.stringify({
      hookSpecificOutput: { hookEventName: 'PreToolUse', permissionDecision, permissionDecisionReason },
    }),
  );
  process.exit(0);
};

// [start, end) offsets of every "<!-- SYNCED FROM framework/… -->" …
// "<!-- END SYNC: … -->" block, marker lines included.
const syncBlocks = (text) => {
  const out = [];
  const re = /^<!-- SYNCED FROM framework\/.*$/gm;
  for (let m; (m = re.exec(text)); ) {
    const end = text.indexOf('<!-- END SYNC:', m.index);
    if (end < 0) break;
    const eol = text.indexOf('\n', end);
    out.push([m.index, eol < 0 ? text.length : eol + 1]);
  }
  return out;
};

if (/^(CLAUDE|AGENTS)\.md$/.test(rel)) {
  let current = '';
  try {
    current = readFileSync(resolve(root, rel), 'utf8');
  } catch {}
  const blocks = syncBlocks(current);
  const reason =
    'This edit changes a framework sync block in ' +
    rel +
    '. The next sync overwrites it — change framework/agents instead and let the sync PR carry it.';
  if (tool === 'Write' && blocks.length) {
    const same = (a, b) => a.length === b.length && a.every(([s, e], i) => current.slice(s, e) === (t.content ?? '').slice(b[i][0], b[i][1]));
    if (!same(blocks, syncBlocks(t.content ?? ''))) decide('deny', reason);
  } else if (tool === 'Edit' || tool === 'MultiEdit') {
    const edits = tool === 'MultiEdit' ? (t.edits ?? []) : [t];
    for (const e of edits) {
      const needle = e.old_string ?? '';
      if (!needle) continue;
      for (let i = current.indexOf(needle); i >= 0; i = current.indexOf(needle, i + 1)) {
        const j = i + needle.length;
        if (blocks.some(([s, en]) => i < en && j > s)) decide('deny', reason);
      }
    }
  }
}

const allow = new Set((process.env.AGENT_GUARD_ALLOW ?? '').split(',').map((s) => s.trim()));
const base = basename(rel);
const protectedClass =
  (rel === '.github' || rel.startsWith('.github/')) ? 'github'
  : /(^|\/)prisma\/migrations\//.test(rel) ? 'migrations'
  : (base === '.envrc' || /^\.env(\..+)?$/.test(base)) ? 'env'
  : (rel === '.claude/settings.json' || rel.startsWith('.claude/hooks/')) ? 'claude'
  : null;

if (protectedClass && !allow.has(protectedClass)) {
  const why = {
    github: 'CI and workflow files are platform-owned; a change here needs a human to confirm it.',
    migrations: 'Migrations are generated by `pnpm db:migrate` from schema.prisma, never written by hand.',
    env: 'Env files can carry secrets; they are not edited by agents.',
    claude: 'This is the agent guardrail itself.',
  }[protectedClass];
  decide('ask', `${rel} is a protected path. ${why}`);
}
